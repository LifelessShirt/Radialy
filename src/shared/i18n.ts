export function translateActionLabel(label: string, language: Language): string {
  for (const values of Object.values(defaultActionLabels)) {
    if (Object.values(values).includes(label)) return values[language];
  }
  return label;
}

export function detectLanguage(locale: string): Language {
  const normalized = locale.toLowerCase().replace('_', '-');
  if (normalized.startsWith('uk')) return 'uk';
  if (normalized.startsWith('ru')) return 'ru';
  return 'en';
}
