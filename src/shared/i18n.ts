export function translate(text: string, language: Language): string {
  return language === 'ru' ? text : translations[language][text] ?? text;
}

export function translateRuntimeError(message: string, language: Language): string {
  const hookPrefix = 'Не удалось запустить перехват клавиш: ';
  if (message.startsWith(hookPrefix)) {
    return translate('Не удалось запустить перехват клавиш: {error}', language).replace('{error}', message.slice(hookPrefix.length));
  }
  const unknownKey = message.match(/^Неизвестная клавиша: «(.+)»$/);
  if (unknownKey) return translate('Неизвестная клавиша: «{key}»', language).replace('{key}', unknownKey[1]);
  return translate(message, language);
}

